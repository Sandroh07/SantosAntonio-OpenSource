CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(190) NOT NULL, sku VARCHAR(80) DEFAULT NULL UNIQUE,
 barcode VARCHAR(120) DEFAULT NULL UNIQUE,
 category_id BIGINT UNSIGNED NULL,
 item_type ENUM('product','service') NOT NULL DEFAULT 'product',
 price_cents BIGINT UNSIGNED NOT NULL,
 stock_qty INT NOT NULL DEFAULT 0,
 low_stock_threshold INT NOT NULL DEFAULT 5,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(190) NOT NULL, email VARCHAR(190) DEFAULT NULL,
 phone VARCHAR(60) DEFAULT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sales (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sale_no VARCHAR(60) UNIQUE DEFAULT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 customer_id BIGINT UNSIGNED NULL,
 subtotal_cents BIGINT UNSIGNED NOT NULL,
 discount_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
 tax_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
 total_cents BIGINT UNSIGNED NOT NULL,
 paid_cents BIGINT UNSIGNED NOT NULL,
 change_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
 payment_method ENUM('cash','card','transfer','mobile') NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id),
 FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL,
 INDEX idx_sales_date(created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sale_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sale_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 item_name VARCHAR(190) NOT NULL,
 qty INT UNSIGNED NOT NULL,
 unit_price_cents BIGINT UNSIGNED NOT NULL,
 line_total_cents BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY (sale_id) REFERENCES sales(id),
 FOREIGN KEY (product_id) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 sale_id BIGINT UNSIGNED DEFAULT NULL,
 actor_user_id BIGINT UNSIGNED NOT NULL,
 delta INT NOT NULL,
 reason ENUM('sale','adjustment') NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (product_id) REFERENCES products(id),
 FOREIGN KEY (sale_id) REFERENCES sales(id),
 FOREIGN KEY (actor_user_id) REFERENCES users(id)
) ENGINE=InnoDB;
