-- UniversalPOS · MySQL 8+ · utf8mb4 · one business per installation
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','cashier') NOT NULL DEFAULT 'cashier',
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 id TINYINT UNSIGNED PRIMARY KEY,
 business_name VARCHAR(190) NOT NULL DEFAULT 'My Business',
 business_type ENUM('retail','restaurant','salon','pharmacy','auto','hardware','services','other') NOT NULL DEFAULT 'retail',
 currency CHAR(3) NOT NULL DEFAULT 'AOA',
 tax_rate_bp INT UNSIGNED NOT NULL DEFAULT 0,
 stock_enabled TINYINT(1) NOT NULL DEFAULT 1,
 receipt_note VARCHAR(500) DEFAULT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
